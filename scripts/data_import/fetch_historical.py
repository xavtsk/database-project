"""Download the explicitly approved Weedle's Cave dataset for offline inspection.

This command only caches source files. It does not create a historical SQL schema
or load battle records. Existing source bytes are never silently overwritten.
"""
import csv
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
import zipfile

import requests

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / "data/raw/historical/weedles_cave"
URL = "https://www.kaggle.com/api/v1/datasets/download/terminus7/pokemon-challenge"
FILES = ("pokemon.csv", "combats.csv", "tests.csv")


def fetch(destination=DESTINATION):
    destination = Path(destination)
    metadata = destination / "source.json"
    if metadata.exists():
        manifest = json.loads(metadata.read_text(encoding="utf-8"))
        for file in manifest["files"]:
            if file["file"] not in FILES:
                raise ValueError("Unexpected cached source entry")
            if hashlib.sha256((destination / file["file"]).read_bytes()).hexdigest() != file["sha256"]:
                raise ValueError("Cached historical source hash differs; inspect it before downloading again")
        if {file["file"] for file in manifest["files"]} != set(FILES):
            raise ValueError("Incomplete historical source manifest")
        print("[CACHED] Historical dataset: source hashes verified; no HTTP request")
        return manifest
    response = requests.get(URL, timeout=30)
    response.raise_for_status()
    if len(response.content) > 20_000_000:
        raise ValueError("Unexpected historical archive size")
    archive = zipfile.ZipFile(io.BytesIO(response.content))
    bodies, entries = {}, []
    for name in FILES:
        matches = [entry for entry in archive.infolist() if not entry.is_dir() and entry.filename.rsplit("/", 1)[-1] == name]
        if len(matches) != 1 or matches[0].file_size > 10_000_000:
            raise ValueError("Unexpected archive entry for " + name)
        body = archive.read(matches[0])
        rows = csv.DictReader(io.StringIO(body.decode("utf-8-sig")))
        count = sum(1 for _ in rows)
        if not rows.fieldnames or count == 0:
            raise ValueError("Empty historical CSV: " + name)
        target = destination / name
        if target.exists() and target.read_bytes() != body:
            raise ValueError("Existing historical source differs: " + name)
        bodies[name] = body
        entries.append(dict(file=name, bytes=len(body), sha256=hashlib.sha256(body).hexdigest(),
                            rows=count, columns=rows.fieldnames))
    manifest = dict(dataset="Pokemon- Weedle's Cave", source_url="https://www.kaggle.com/terminus7/pokemon-challenge",
                    download_url=URL, retrieved_at=datetime.now(timezone.utc).isoformat(), license="CC0: Public Domain",
                    battle_data="Generated by the source author's custom algorithm; the first participant attacks first.",
                    archive_sha256=hashlib.sha256(response.content).hexdigest(), files=entries)
    destination.mkdir(parents=True, exist_ok=True)
    for name, body in bodies.items():
        temporary = (destination / name).with_suffix(".csv.tmp")
        temporary.write_bytes(body)
        temporary.replace(destination / name)
    metadata.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    for entry in entries:
        print(f"[CACHED] {entry['file']}: {entry['rows']} rows; columns {entry['columns']}")
    return manifest


if __name__ == "__main__":
    fetch()
